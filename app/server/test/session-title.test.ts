import { describe, expect, it } from 'vitest';
import { clampTitle, sessionTitle, skillOf, substantiveLine, TITLE_MAX } from '../src/archive/sessionTitle.js';

// Shapes copied from real harness prompts, with made-up content.
const REMINDER = '<system-reminder>\nCodebase and user instructions are shown below.\nContents of /home/someone/AGENTS.md (project instructions):\n# AGENTS.md\nNever commit to main.\n</system-reminder>';
const AGENTS_BLOCK = '# AGENTS.md: rules for agents changing the engine\n\nThis repo is the public engine...';
const CODEX_AGENTS = '# AGENTS.md instructions for /work/repo\n\n<INSTRUCTIONS>\nbe careful\n</INSTRUCTIONS>';
const CODEX_ENV = '<environment_context>\n  <cwd>/work/repo</cwd>\n</environment_context>';
const CLEAR = '<command-name>/clear</command-name>\n<command-message>clear</command-message>\n<command-args></command-args>';
const CAVEAT = '<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>';
const SKILL = '<command-message>argo-daily-update is running…</command-message>\n<command-name>/argo-daily-update</command-name>';
const TELEGRAM = '<channel source="plugin:telegram:telegram" chat_id="1" user="someone">\nwhat is on the board today?\n</channel>';

describe('session titles', () => {
  it('prefers the trusted card title over everything', () => {
    expect(sessionTitle({ taskTitle: 'Usage sessions: Telegram inspection', title: 'Some ai title', prompts: [REMINDER] }))
      .toEqual({ text: 'Usage sessions: Telegram inspection', source: 'task' });
  });

  it('names a skill run after the skill, skipping local commands first', () => {
    expect(sessionTitle({ prompts: [CAVEAT, CLEAR, SKILL] })).toEqual({ text: 'argo-daily-update', source: 'skill' });
    expect(skillOf(CLEAR)).toBeNull();
    expect(skillOf('/compact keep the plan')).toBeNull();
    expect(skillOf('/argo-news today')).toBe('argo-news');
    expect(skillOf('Base directory for this skill: /vault/.agents/skills/caption-video\n\n# Caption')).toBe('caption-video');
  });

  it('rejects instruction blocks, environment context and system notes as titles', () => {
    for (const block of [REMINDER, AGENTS_BLOCK, CODEX_AGENTS, CODEX_ENV, CLEAR, CAVEAT,
      'This session is being continued from a previous conversation that ran out of context.',
      '[SYSTEM: scheduled job]', 'You are running headless on card t_1', 'You are rune, Platform engineer at Example',
      '<user-prompt-submit-hook>noise</user-prompt-submit-hook>']) {
      expect(substantiveLine(block), block).toBeNull();
    }
    // The real request after the boilerplate becomes the name.
    expect(sessionTitle({ prompts: [CODEX_AGENTS, CODEX_ENV, 'Fix the flaky login test'] })).toEqual({ text: 'Fix the flaky login test', source: 'prompt' });
    expect(sessionTitle({ prompts: [`${REMINDER}\nBoard card t_1: Make the page faster\n\nmore detail`] }))
      .toEqual({ text: 'Board card t_1: Make the page faster', source: 'prompt' });
  });

  it('a boilerplate harness title is not used; a good one is', () => {
    expect(sessionTitle({ title: AGENTS_BLOCK, prompts: ['tidy the inbox'] })).toEqual({ text: 'tidy the inbox', source: 'prompt' });
    expect(sessionTitle({ title: 'Inbox cleanup plan', prompts: ['tidy the inbox'] })).toEqual({ text: 'Inbox cleanup plan', source: 'title' });
  });

  it('strips the Telegram transport wrapper', () => {
    expect(sessionTitle({ prompts: [TELEGRAM] })).toEqual({ text: 'what is on the board today?', source: 'prompt' });
  });

  it('a real request before a later slash command keeps the request', () => {
    expect(sessionTitle({ prompts: ['write the release notes', '/argo-news'] })?.source).not.toBe('skill');
  });

  it('is one line and strictly under 100 characters', () => {
    const long = `Please ${'refactor the usage page and '.repeat(10)}done`;
    const t = sessionTitle({ prompts: [long] })!;
    expect(t.text.length).toBeLessThan(100);
    expect(t.text.length).toBeLessThanOrEqual(TITLE_MAX);
    expect(t.text.endsWith('…')).toBe(true);
    expect(clampTitle('a\nb\t c')).toBe('a b c');
    expect(clampTitle('x'.repeat(300)).length).toBeLessThan(100);
  });

  it('returns null when nothing is usable, so the caller shows the id explicitly', () => {
    expect(sessionTitle({ prompts: [REMINDER, CLEAR] })).toBeNull();
    expect(sessionTitle({})).toBeNull();
  });
});
