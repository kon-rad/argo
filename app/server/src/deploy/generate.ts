/**
 * `secondbrain plan|apply`: the env file and systemd units a server should have,
 * generated from the `server` block in `secondbrain.json` and the enabled feature
 * manifests, and the diff against what is on disk today (proposal section 4).
 *
 * Pure by design. It reads files through an injected `read` and writes nothing
 * itself, so `plan` can print a diff and a test can exercise it without touching
 * `/etc`. `apply` is the only thing that writes, and only to a plan it was given.
 *
 * Generation sits behind `server.generate: true` (off by default) so a merge never
 * changes a running server's units on its own; the owner turns it on and runs
 * `secondbrain apply`. See docs/configuration.md.
 */
import { basename, join } from 'node:path';
import { enabledManifests } from '../features/registry.js';
import type { ServerSettings } from '../settings.js';

export type { ServerSettings };

/** Keys the generated env file always carries, whatever the module list, in this order. */
const SERVER_BASE_KEYS = [
  'DEPLOYMENT',
  'PUBLIC_ORIGIN',
  'VAULT_ROOT',
  'DATABASE_URL',
  'PORT',
  'SCAN_INTERVAL_MINUTES',
  'MODULES',
  'OWNER_NAME',
] as const;

/** Secrets the server needs whatever the module list: the login. */
const SERVER_SECRET_KEYS = ['AUTH_PASSWORD_HASH', 'AUTH_TOTP_SECRET'] as const;

/** The unit every server installs (the app itself), before any feature's timers. */
const ALWAYS_UNITS = ['secondbrain'] as const;

/** The systemd unit stems this install owns: the app service, then each enabled feature's timers. */
export function unitStems(modules: ReadonlySet<string>): string[] {
  return [...ALWAYS_UNITS, ...enabledManifests(modules).flatMap((m) => m.timers.map((t) => t.unit))];
}

/** The env keys the generated `/etc/secondbrain/env` holds: the server block plus each enabled feature's `env`. */
export function envKeys(modules: ReadonlySet<string>): string[] {
  const fromFeatures = enabledManifests(modules).flatMap((m) => m.env);
  return [...new Set<string>([...SERVER_BASE_KEYS, ...SERVER_SECRET_KEYS, ...fromFeatures])];
}

/** The values behind the base keys, from the server block (and machine identity where the block has none). */
function baseEnv(server: ServerSettings, modules: ReadonlySet<string>, values: Record<string, string | undefined>): Record<string, string> {
  const origin = server.publicOrigin ?? (server.host ? `https://${server.host}` : (values.PUBLIC_ORIGIN ?? ''));
  return {
    DEPLOYMENT: 'server',
    PUBLIC_ORIGIN: origin,
    VAULT_ROOT: server.vaultDir,
    DATABASE_URL: values.DATABASE_URL ?? 'postgres:///secondbrain?host=/var/run/postgresql',
    PORT: values.PORT ?? '5123',
    SCAN_INTERVAL_MINUTES: values.SCAN_INTERVAL_MINUTES ?? '30',
    MODULES: [...modules].join(','),
    OWNER_NAME: values.OWNER_NAME ?? 'owner',
  };
}

/** The env file's content: base keys from the server block, every other key from the source (or empty). */
export function renderEnv(server: ServerSettings, modules: ReadonlySet<string>, values: Record<string, string | undefined>): string {
  const base = baseEnv(server, modules, values);
  const lines = [
    '# /etc/secondbrain/env - generated by `secondbrain apply` from secondbrain.json and the',
    '# feature manifests. Do not edit by hand: edit the `server` block and re-run apply.',
    `# Owner root:${server.user}, mode 640.`,
  ];
  for (const key of envKeys(modules)) lines.push(`${key}=${base[key] ?? values[key] ?? ''}`);
  return `${lines.join('\n')}\n`;
}

/** The `@...@` placeholders the unit templates carry, resolved from the server block. */
export function unitSubstitutions(server: ServerSettings): Record<string, string> {
  return {
    '@APP_USER@': server.user,
    '@APP_DIR@': server.dir,
    '@VAULT_DIR@': server.vaultDir,
    '@APP_HOME@': `/home/${server.user}`,
    '@HERMES_HOME@': server.hermesHome ?? `/home/${server.user}/.hermes`,
  };
}

export function renderUnit(template: string, subs: Record<string, string>): string {
  let out = template;
  for (const [k, v] of Object.entries(subs)) out = out.split(k).join(v);
  return out;
}

export type PlannedFileKind = 'env' | 'unit';
export type PlannedFileStatus = 'create' | 'update' | 'unchanged';

export interface PlannedFile {
  kind: PlannedFileKind;
  /** Absolute path the file is written to. */
  path: string;
  /** What is on disk now, or undefined when the file does not exist yet. */
  before?: string;
  /** What it should hold. */
  after: string;
  status: PlannedFileStatus;
}

export interface DeployPlan {
  files: PlannedFile[];
  /** Unit files installed but not owned by this build. Reported, never removed by `apply`. */
  stale: string[];
  /** The subset of `files` that differ and would be written. */
  changed: PlannedFile[];
}

export interface PlanInput {
  server: ServerSettings;
  modules: ReadonlySet<string>;
  /** Where the unit templates live (`app/deploy`). */
  templateDir: string;
  /** Where the units are installed (`/etc/systemd/system`). */
  unitDir: string;
  /** The env file's path (`/etc/secondbrain/env`). */
  envPath: string;
  /** Values for the non-base env keys, from the vault's `.env` or the environment. */
  values: Record<string, string | undefined>;
  /** Reads a file, or returns undefined when it does not exist. Injected so a plan is testable and writes nothing. */
  read: (path: string) => string | undefined;
  /** The unit files already installed, so stale ones can be reported. */
  installed: string[];
}

export function planDeploy(input: PlanInput): DeployPlan {
  const subs = unitSubstitutions(input.server);
  const files: PlannedFile[] = [];
  const add = (kind: PlannedFileKind, path: string, after: string): void => {
    const before = input.read(path);
    files.push({ kind, path, before, after, status: before === undefined ? 'create' : before === after ? 'unchanged' : 'update' });
  };

  add('env', input.envPath, renderEnv(input.server, input.modules, input.values));
  for (const stem of unitStems(input.modules)) {
    // A unit may exist as a service only (the app) or as a service + timer (a feature's sweep).
    for (const ext of ['service', 'timer']) {
      const name = `${stem}.${ext}`;
      const template = input.read(join(input.templateDir, name));
      if (template === undefined) continue;
      add('unit', join(input.unitDir, name), renderUnit(template, subs));
    }
  }

  const owned = new Set(files.filter((f) => f.kind === 'unit').map((f) => basename(f.path)));
  const stale = input.installed.filter((f) => f.startsWith('secondbrain') && !owned.has(f));
  return { files, stale, changed: files.filter((f) => f.status !== 'unchanged') };
}

export interface ApplyResult {
  written: string[];
  unchanged: string[];
}

/** Write the changed files of a plan. Deliberately never removes a stale unit: that is a person's call. */
export function applyDeploy(plan: DeployPlan, write: (path: string, content: string) => void): ApplyResult {
  const written: string[] = [];
  const unchanged: string[] = [];
  for (const f of plan.files) {
    if (f.status === 'unchanged') {
      unchanged.push(f.path);
      continue;
    }
    write(f.path, f.after);
    written.push(f.path);
  }
  return { written, unchanged };
}
