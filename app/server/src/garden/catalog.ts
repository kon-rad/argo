import { readFile } from 'node:fs/promises';
import { join } from 'node:path';
import type { RuleContext } from './rules.js';
import type { Shelf } from './shelves.js';

/**
 * The card catalog: one table per root, one row per shelf, rendered from the
 * shelf headers. Generated nightly; the owner changes a row by editing the
 * shelf's note, never this file.
 */
export interface CatalogFacts {
  noteCount: (dir: string) => number;
  nextAction: (dir: string) => string | null;
}

/** The `- **Next action:**` line of `<dir>/dev-log/README.md`, when the shelf keeps a Resume block. */
export async function readNextAction(root: string, dir: string): Promise<string | null> {
  let text: string;
  try { text = await readFile(join(root, dir, 'dev-log', 'README.md'), 'utf8'); } catch { return null; }
  const m = /^\s*-\s*\*\*Next action:\*\*\s*(.+?)\s*$/m.exec(text);
  return m ? m[1]! : null;
}

const NEXT_ACTION_MAX = 160;

function cell(s: string | null | undefined, max = 0): string {
  let v = (s ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
  if (max > 0 && v.length > max) v = `${v.slice(0, max - 1).trimEnd()}…`;
  return v;
}

export function renderCatalog(shelves: Shelf[], ctx: RuleContext, facts: CatalogFacts): string {
  const lines: string[] = [
    '# Catalog',
    '',
    `Generated by secondbrain garden on ${ctx.today}. Edit a shelf's README to change a row.`,
    '',
  ];
  for (const root of ctx.settings.roots) {
    const rows = shelves
      .filter((s) => s.dir.startsWith(`${root}/`))
      .map((s) => ({ s, touched: ctx.lastTouched(s.dir) ?? '' }))
      .sort((a, b) => b.touched.localeCompare(a.touched) || a.s.dir.localeCompare(b.s.dir));
    if (rows.length === 0) continue;
    lines.push(`## ${root}`, '', `${rows.length} shelves.`, '', '| Shelf | Status | Project | Notes | Last touched | Reviewed | Next action |', '|---|---|---|---|---|---|---|');
    for (const { s, touched } of rows) {
      lines.push(`| ${cell(s.dir)} | ${s.meta.status} | ${cell(s.meta.project)} | ${facts.noteCount(s.dir)} | ${touched || 'none'} | ${s.meta.last_reviewed} | ${cell(facts.nextAction(s.dir), NEXT_ACTION_MAX)} |`);
    }
    lines.push('');
  }
  return `${lines.join('\n').replace(/\n+$/, '')}\n`;
}
