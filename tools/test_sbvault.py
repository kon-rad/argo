"""Tests for the vault CLI (tools/sbvault.py). Run: python3 -m pytest tools"""
import hashlib
import os
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

ENGINE_SRC = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ENGINE_SRC / "tools"))
import sbvault  # noqa: E402


@pytest.fixture
def vault(tmp_path):
    """A vault holding a copy of the engine at .secondbrain/ (template, skills, tools)."""
    v = tmp_path / "vault"
    eng = v / ".secondbrain"
    for part in ("vault-template", "skills", "tools", "harness"):
        shutil.copytree(ENGINE_SRC / part, eng / part, ignore=shutil.ignore_patterns("__pycache__", ".pytest_cache"))
    return v


def cli(vault, *args):
    return subprocess.run([sys.executable, str(vault / ".secondbrain" / "tools" / "sbvault.py"), *args],
                          capture_output=True, text=True, cwd=vault, timeout=30)


# ---- rules ----

def test_rules_composes_base_then_local(vault):
    (vault / "AGENTS.local.md").write_text("## Mine\n\nMy rule.\n")
    assert cli(vault, "rules").returncode == 0
    text = (vault / "AGENTS.md").read_text()
    header, body = text.split("\n", 1)
    assert header.startswith("<!-- generated by secondbrain-vault rules")
    base = (vault / ".secondbrain" / "vault-template" / "AGENTS.base.md").read_text()
    assert body.index(base.strip().splitlines()[0]) < body.index("## Mine")
    assert hashlib.sha256(body.encode()).hexdigest() in header


def test_rules_refuses_a_hand_edited_file(vault):
    (vault / "AGENTS.local.md").write_text("## Mine\n")
    cli(vault, "rules")
    f = vault / "AGENTS.md"
    f.write_text(f.read_text() + "\nA rule someone added by hand.\n")
    p = cli(vault, "rules")
    assert p.returncode == 3
    assert "edited by hand" in p.stderr
    assert "A rule someone added by hand." in f.read_text()


def test_rules_refuses_a_file_it_did_not_write(vault):
    (vault / "AGENTS.md").write_text("# Old hand-written rules\n")
    (vault / "AGENTS.local.md").write_text("## Mine\n")
    assert cli(vault, "rules").returncode == 3
    assert (vault / "AGENTS.md").read_text() == "# Old hand-written rules\n"


def test_rules_force_overwrites(vault):
    (vault / "AGENTS.md").write_text("# Old\n")
    (vault / "AGENTS.local.md").write_text("## Mine\n")
    assert cli(vault, "rules", "--force").returncode == 0
    assert "## Mine" in (vault / "AGENTS.md").read_text()


def test_rules_is_idempotent(vault):
    (vault / "AGENTS.local.md").write_text("## Mine\n")
    cli(vault, "rules")
    first = (vault / "AGENTS.md").read_text()
    assert cli(vault, "rules").returncode == 0
    assert (vault / "AGENTS.md").read_text() == first


def test_rules_check_mode_reports_drift(vault):
    (vault / "AGENTS.local.md").write_text("## Mine\n")
    cli(vault, "rules")
    assert cli(vault, "rules", "--check").returncode == 0
    (vault / "AGENTS.local.md").write_text("## Mine, changed\n")
    assert cli(vault, "rules", "--check").returncode == 1


# ---- link-skills ----

def test_link_skills_links_engine_skills(vault):
    assert cli(vault, "link-skills").returncode == 0
    link = vault / ".agents" / "skills" / "fact-check"
    assert link.is_symlink()
    assert not os.path.isabs(os.readlink(link))
    assert (link / "SKILL.md").is_file()


def test_link_skills_private_dir_wins(vault):
    private = vault / ".agents" / "skills" / "fact-check"
    private.mkdir(parents=True)
    (private / "SKILL.md").write_text("mine")
    p = cli(vault, "link-skills")
    assert p.returncode == 0
    assert not private.is_symlink()
    assert (private / "SKILL.md").read_text() == "mine"
    assert "private" in p.stdout


def test_link_skills_removes_dangling_engine_links(vault):
    skills = vault / ".agents" / "skills"
    skills.mkdir(parents=True)
    (skills / "gone").symlink_to(Path("..") / ".." / ".secondbrain" / "skills" / "gone")
    (skills / "theirs").symlink_to(Path("/nonexistent/elsewhere"))
    cli(vault, "link-skills")
    assert not os.path.lexists(skills / "gone")
    assert os.path.lexists(skills / "theirs")  # not ours to remove


# ---- init ----

def test_init_builds_a_working_vault(vault):
    p = cli(vault, "init", ".")
    assert p.returncode == 0, p.stderr
    for rel in ("AGENTS.md", "AGENTS.local.md", "CLAUDE.md", "PARA Guide.md", ".gitignore", ".env.example",
                "Projects/README.md", "Areas/README.md", "Research/README.md", "Archives/README.md",
                ".agents/guard.local.json", ".claude/settings.json", "zen.example.json"):
        assert (vault / rel).exists(), rel
    assert (vault / ".claude" / "skills").is_symlink()
    assert (vault / ".claude" / "skills" / "fact-check" / "SKILL.md").is_file()
    assert (vault / "CLAUDE.md").read_text().strip().endswith("@AGENTS.md")
    assert ".secondbrain/harness/hooks/guard.py" in (vault / ".claude" / "settings.json").read_text()
    assert not (vault / "AGENTS.base.md").exists()
    assert cli(vault, "rules", "--check").returncode == 0


def test_init_refuses_a_vault_with_content(vault):
    (vault / "notes.md").write_text("hi")
    p = cli(vault, "init", ".")
    assert p.returncode == 2
    assert not (vault / "AGENTS.md").exists()


def test_init_allows_git_files(vault):
    (vault / ".git").mkdir()
    (vault / ".gitmodules").write_text("")
    assert cli(vault, "init", ".").returncode == 0


def test_template_gitignore_keeps_secrets_out():
    g = (ENGINE_SRC / "vault-template" / "gitignore").read_text()
    for line in (".env", "*.db", "CLAUDE.local.md"):
        assert line in g.splitlines()


def test_base_rules_are_generic():
    base = (ENGINE_SRC / "vault-template" / "AGENTS.base.md").read_text()
    for rule in ("markdown", "Projects/", "kebab-case", "confirmed vs. inferred", ".env", "AGENTS.local.md"):
        assert rule in base, rule
