#!/usr/bin/env python3
"""secondbrain-vault: set up and maintain a vault that uses this engine.

  init [DIR]          start a vault in DIR (default: the vault around this engine)
  rules [--check] [--force]
                      write AGENTS.md = the engine's AGENTS.base.md + the vault's AGENTS.local.md
  link-skills         symlink the engine's skills into <vault>/.agents/skills/
  sync ...            keep this checkout in step with your other machines (tools/sbsync.py, docs/sync.md)

The vault is DIR for init; otherwise --vault, else the folder that holds this
engine as .secondbrain/, else the current directory. Stdlib only: it runs on
any machine with Python 3.9+.
"""
import argparse
import hashlib
import os
import shutil
import sys
from pathlib import Path

ENGINE = Path(__file__).resolve().parents[1]
TEMPLATE = ENGINE / "vault-template"
SKILLS = ENGINE / "skills"
HARNESS = ENGINE / "harness"
MARK = "<!-- generated by secondbrain-vault rules"
# Files the template stores without their leading dot, so they don't act on the engine repo itself.
RENAMED = {"gitignore": ".gitignore", "env.example": ".env.example"}
# What may already be in a folder that `init` is allowed to turn into a vault.
INIT_OK = {".git", ".gitmodules", ".secondbrain", ".DS_Store"}
GUARD_LOCAL = '{\n  "protected_dirs": [],\n  "no_delete": [],\n  "readonly": []\n}\n'


def default_vault() -> Path:
    if ENGINE.name == ".secondbrain":
        return ENGINE.parent
    return Path.cwd()


def say(msg: str) -> None:
    print(msg)


def fail(msg: str, code: int) -> int:
    print(f"secondbrain-vault: {msg}", file=sys.stderr)
    return code


# ---- rules ----

def compose(vault: Path) -> str:
    base = (TEMPLATE / "AGENTS.base.md").read_text().rstrip() + "\n"
    local_file = vault / "AGENTS.local.md"
    local = local_file.read_text().strip() if local_file.exists() else ""
    body = base + ("\n---\n\n" + local + "\n" if local else "")
    digest = hashlib.sha256(body.encode()).hexdigest()
    header = (f"{MARK} from .secondbrain/vault-template/AGENTS.base.md + AGENTS.local.md; "
              f"edit those, not this file; sha256:{digest} -->")
    return header + "\n" + body


def hand_edited(text: str) -> bool:
    """True if this AGENTS.md wasn't written by `rules`, or was changed after it was."""
    header, _, body = text.partition("\n")
    if not header.startswith(MARK) or "sha256:" not in header:
        return True
    want = header.split("sha256:", 1)[1].split()[0]
    return hashlib.sha256(body.encode()).hexdigest() != want


def cmd_rules(vault: Path, check: bool, force: bool) -> int:
    target = vault / "AGENTS.md"
    new = compose(vault)
    old = target.read_text() if target.exists() else None
    if check:
        if old == new:
            say("AGENTS.md is up to date")
            return 0
        return fail("AGENTS.md is out of date: run `secondbrain-vault rules`", 1)
    if old == new:
        say("AGENTS.md is up to date")
        return 0
    if old is not None and hand_edited(old) and not force:
        return fail("AGENTS.md was edited by hand (or not written by this tool). Move those edits into "
                    "AGENTS.local.md, then rerun; --force overwrites it.", 3)
    target.write_text(new)
    say(f"wrote {target}")
    return 0


# ---- link-skills ----

def points_into_engine_skills(link: Path) -> bool:
    dest = os.path.normpath(os.path.join(link.parent, os.readlink(link)))
    return Path(dest).parent.name == "skills" and Path(dest).parent.parent.name in {".secondbrain", ENGINE.name}


def cmd_link_skills(vault: Path) -> int:
    skills_dir = vault / ".agents" / "skills"
    skills_dir.mkdir(parents=True, exist_ok=True)
    for entry in sorted(skills_dir.iterdir()):
        if entry.is_symlink() and not entry.exists() and points_into_engine_skills(entry):
            entry.unlink()
            say(f"removed dangling link {entry.name}")
    if not SKILLS.is_dir():
        return 0
    for skill in sorted(p for p in SKILLS.iterdir() if (p / "SKILL.md").is_file()):
        link = skills_dir / skill.name
        rel = os.path.relpath(skill, skills_dir)
        if link.is_symlink():
            if os.readlink(link) == rel:
                continue
            if not points_into_engine_skills(link):
                say(f"kept {skill.name}: links somewhere else")
                continue
            link.unlink()
        elif link.exists():
            say(f"kept {skill.name}: a private skill of that name wins")
            continue
        link.symlink_to(rel)
        say(f"linked {skill.name}")
    return 0


# ---- init ----

def cmd_init(vault: Path) -> int:
    vault.mkdir(parents=True, exist_ok=True)
    extra = sorted(p.name for p in vault.iterdir() if p.name not in INIT_OK)
    if extra:
        return fail(f"{vault} already has content ({', '.join(extra[:5])}); init only starts new vaults", 2)
    for src in TEMPLATE.rglob("*"):
        rel = src.relative_to(TEMPLATE)
        if rel.name == "AGENTS.base.md" or src.is_dir():
            continue
        dest = vault / rel.parent / RENAMED.get(rel.name, rel.name)
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dest)
    (vault / ".agents" / "skills").mkdir(parents=True, exist_ok=True)
    (vault / ".agents" / "guard.local.json").write_text(GUARD_LOCAL)
    claude = vault / ".claude"
    (claude / "agents").mkdir(parents=True, exist_ok=True)
    shutil.copy2(HARNESS / "claude" / "settings.json", claude / "settings.json")
    for agent in (HARNESS / "claude" / "agents").glob("*.md"):
        shutil.copy2(agent, claude / "agents" / agent.name)
    if not (claude / "skills").exists():
        (claude / "skills").symlink_to(Path("..") / ".agents" / "skills")
    rc = cmd_rules(vault, check=False, force=False)
    if rc:
        return rc
    cmd_link_skills(vault)
    say(f"vault ready at {vault}. Next: cp .env.example .env, then read AGENTS.md")
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="secondbrain-vault", description=__doc__.split("\n\n")[0])
    ap.add_argument("--vault", type=Path)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p_init = sub.add_parser("init", help="start a new vault")
    p_init.add_argument("dir", nargs="?", type=Path)
    p_rules = sub.add_parser("rules", help="compile AGENTS.md")
    p_rules.add_argument("--check", action="store_true", help="exit 1 if AGENTS.md is out of date")
    p_rules.add_argument("--force", action="store_true", help="overwrite a hand-edited AGENTS.md")
    sub.add_parser("link-skills", help="link the engine's skills into .agents/skills")
    p_sync = sub.add_parser("sync", help="commit, pull and push this checkout on a timer (see docs/sync.md)")
    p_sync.add_argument("rest", nargs=argparse.REMAINDER, help="run | status | install | uninstall | resolve")
    args = ap.parse_args(argv)

    if args.cmd == "init":
        return cmd_init((args.dir or args.vault or default_vault()).resolve())
    vault = (args.vault or default_vault()).resolve()
    if args.cmd == "sync":
        import sbsync
        return sbsync.main(args.rest or ["--help"], vault=vault)
    if args.cmd == "rules":
        return cmd_rules(vault, args.check, args.force)
    return cmd_link_skills(vault)


if __name__ == "__main__":
    sys.exit(main())
